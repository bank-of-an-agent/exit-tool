// Vendors the Agent Bank contract artifacts the shutdown drill deploys (see vendor-contracts.sh).
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { keccak256 } from "viem";

/** Every contract the drill deploys, and nothing else. */
const CONTRACTS = [
  "AgentEscrow",
  "PaymentStreams",
  "TimeLockVaults",
  "TopUpExecutor",
  "SweepExecutor",
  "AgentPolicyHook",
  "MockUSDC",
  "MockTreasuryFund",
  "MockValidationRegistry",
];

const args = process.argv.slice(2);
const allowDirty = args.includes("--allow-dirty");
const [outDir, destDir] = args.filter((a) => !a.startsWith("--"));
if (!outDir || !destDir) {
  console.error("usage: node scripts/vendor-contracts.mjs [--allow-dirty] <contracts-out-dir> <dest-dir>");
  process.exit(1);
}
const fail = (message) => {
  console.error(`error: ${message}`);
  process.exit(1);
};
if (!fs.existsSync(outDir)) {
  fail(
    `${outDir} does not exist: run \`forge build\` in the contracts repository, or pass its out/ directory.`,
  );
}
// Foundry writes out/ at the project root, which is where the metadata's source paths start.
const projectRoot = path.dirname(path.resolve(outDir));

function git(gitArgs) {
  try {
    return execFileSync("git", ["-C", projectRoot, ...gitArgs], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch {
    return undefined;
  }
}

const commit = git(["rev-parse", "HEAD"]);
if (!commit) fail(`${projectRoot} is not a git checkout: the contracts commit cannot be recorded.`);
const changes = git(["status", "--porcelain", "--", "src", "lib", "foundry.toml", "remappings.txt"]) ?? "";
if (changes !== "" && !allowDirty) {
  fail(
    `the contracts checkout has uncommitted changes in its sources:\n${changes}\n` +
      "Commit them (the artifacts must match a commit), or pass --allow-dirty to record that they do not.",
  );
}

const compilers = new Set();
const checked = new Set();
const stale = [];
const files = [];
for (const name of CONTRACTS) {
  const file = path.join(outDir, `${name}.sol`, `${name}.json`);
  if (!fs.existsSync(file)) fail(`${file} is missing: run \`forge build\` in ${projectRoot}.`);
  const json = JSON.parse(fs.readFileSync(file, "utf8"));
  const abi = json.abi;
  const bytecode = json.bytecode?.object ?? json.bytecode;
  if (!Array.isArray(abi)) fail(`${file}: no ABI.`);
  if (typeof bytecode !== "string" || !/^0x[0-9a-fA-F]+$/.test(bytecode)) {
    fail(`${file}: no creation bytecode, or unlinked library references (not supported).`);
  }
  // Refuse artifacts built from sources other than the ones checked out: the recorded commit would lie.
  const metadata = typeof json.metadata === "string" ? JSON.parse(json.metadata) : json.metadata;
  if (!metadata?.sources) fail(`${file}: no metadata; build with Foundry's default extra output.`);
  for (const [source, info] of Object.entries(metadata.sources)) {
    const local = path.join(projectRoot, source);
    if (!fs.existsSync(local) || keccak256(fs.readFileSync(local)) !== info.keccak256) {
      stale.push(`${name}: ${source}`);
    }
    checked.add(source);
  }
  const optimizer = metadata.settings?.optimizer;
  compilers.add(
    `solc ${metadata.compiler?.version}, optimizer ${optimizer?.enabled ? `enabled (${optimizer.runs} runs)` : "disabled"}, EVM ${metadata.settings?.evmVersion}${metadata.settings?.viaIR ? ", via IR" : ""}`,
  );
  // Only what the drill uses: the interface and the creation bytecode.
  const body = `${JSON.stringify({ contractName: name, abi, bytecode }, null, 2)}\n`;
  files.push({ name: `${name}.json`, body, sha256: createHash("sha256").update(body).digest("hex") });
}
if (stale.length > 0) {
  fail(
    `the artifacts in ${outDir} were not built from the sources checked out in ${projectRoot}:\n  ${stale.join("\n  ")}\n` +
      "Run `forge build` there first.",
  );
}

fs.mkdirSync(destDir, { recursive: true });
for (const old of fs.readdirSync(destDir)) {
  if (old.endsWith(".json")) fs.rmSync(path.join(destDir, old));
}
for (const f of files) fs.writeFileSync(path.join(destDir, f.name), f.body);
const source = [
  "Agent Bank contract artifacts deployed by the shutdown drill: ABI and creation bytecode only.",
  "Generated by scripts/vendor-contracts.sh from a Foundry build of the contracts repository; do not",
  "edit by hand.",
  "",
  `commit: ${commit}`,
  `uncommitted source changes: ${changes === "" ? "none" : "yes (--allow-dirty)"}`,
  `compiler: ${[...compilers].join("; ")}`,
  `sources: all ${checked.size} source files recorded in the artifacts' metadata match the checkout`,
  "",
  "sha256 of each file (sha256sum -c format):",
  ...files.map((f) => `${f.sha256}  ${f.name}`),
  "",
].join("\n");
fs.writeFileSync(path.join(destDir, "SOURCE"), source);
console.log(
  `vendored ${files.length} artifacts into ${path.relative(process.cwd(), destDir) || destDir} from ${projectRoot} (commit ${commit.slice(0, 12)}${changes === "" ? "" : ", dirty"})`,
);

// Generates src/core/abis/generated/agentbank.ts from the contracts repository (see sync-abis.sh).
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const CONTRACTS = [
  ["AgentEscrow", "agentEscrowAbi"],
  ["PaymentStreams", "paymentStreamsAbi"],
  ["TimeLockVaults", "timeLockVaultsAbi"],
  ["TopUpExecutor", "topUpExecutorAbi"],
  ["SweepExecutor", "sweepExecutorAbi"],
  ["AgentPolicyHook", "agentPolicyHookAbi"],
];

const [contractsDir, outFile] = process.argv.slice(2);
if (!contractsDir || !outFile) {
  console.error("usage: node scripts/gen-abis.mjs <contracts-dir> <out-file>");
  process.exit(1);
}

function loadAbi(name) {
  const candidates = [
    path.join(contractsDir, "abis", `${name}.json`),
    path.join(contractsDir, "abis", `${name}.abi.json`),
    path.join(contractsDir, "out", `${name}.sol`, `${name}.json`),
  ];
  for (const file of candidates) {
    if (!fs.existsSync(file)) continue;
    const raw = fs.readFileSync(file);
    const json = JSON.parse(raw.toString("utf8"));
    const abi = Array.isArray(json) ? json : json.abi;
    if (!Array.isArray(abi)) throw new Error(`${file}: no ABI array found`);
    // Hash the ABI only (not the bytecode), so a recompile without interface changes is not drift.
    const abiSha256 = createHash("sha256").update(JSON.stringify(abi)).digest("hex");
    return { abi, file: path.relative(contractsDir, file), abiSha256 };
  }
  throw new Error(`no ABI for ${name} in ${contractsDir} (tried abis/ and out/; run \`forge build\` there)`);
}

function git(args) {
  try {
    return execFileSync("git", ["-C", contractsDir, ...args], { encoding: "utf8" }).trim();
  } catch {
    return undefined;
  }
}

const commit = git(["rev-parse", "HEAD"]) ?? "unknown";
const dirty = (git(["status", "--porcelain", "--", "src"]) ?? "") !== "";

let body = `// GENERATED by scripts/sync-abis.sh. Do not edit by hand.
//
// Source: the Agent Bank contracts repository (commit ${commit}${dirty ? ", with uncommitted changes under src/" : ""}).
// Regenerate with \`pnpm sync-abis\` after the contracts change, review the diff, and update the
// exit tool if a function it uses changed.

`;
const sources = {};
for (const [name, exportName] of CONTRACTS) {
  const { abi, file, abiSha256 } = loadAbi(name);
  sources[name] = { file, abiSha256 };
  body += `export const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
body += `/** Where these ABIs came from (used by tests to detect drift against a local contracts checkout). */\n`;
body += `export const agentBankAbiSource = ${JSON.stringify({ commit, dirtySources: dirty, artifacts: sources }, null, 2)} as const;\n`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, body);
console.log(
  `wrote ${path.relative(process.cwd(), outFile)} from ${contractsDir} (commit ${commit.slice(0, 12)}${dirty ? ", dirty" : ""})`,
);
